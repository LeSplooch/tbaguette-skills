//! The three delegation roles rendered as custom agents, for Copilot CLI
//! (`com.github.copilot/agents/*.agent.md`) and Claude Code (`agents/*.md`);
//! `site/atelier agents` renders them, `site/atelier agents --check` and the
//! `agents-*` gates keep them current.
//!
//! Sources are `scripts/copilot_agents/<name>.md`. Two tokens pull text out of
//! delegating-tasks-with-review-gates' own dispatch templates, so an agent can
//! never drift from the skill it serves:
//!
//! - `{{IMPLEMENTER_DISCIPLINE}}`: implementer-prompt.md's prompt, from
//!   "## You Do Not Dispatch Subagents" to its end;
//! - `{{REVIEWER_SHARED}}`: reviewer-prompt.md's shared reviewer discipline
//!   (its first fenced block).
//!
//! Both harnesses share one body; only the frontmatter's tool list is
//! translated, from Copilot's tool categories to Claude Code's tool names. A
//! template whose shape changes fails the render loudly rather than shipping
//! an agent with a hole in it.

use std::collections::BTreeMap;
use std::path::Path;
use std::process::ExitCode;

use anyhow::{Context, Result, anyhow, bail};
use regex::Regex;

use super::{Repo, root_from};

/// Copilot's documented ceiling for an agent profile's body.
const MAX_BODY: usize = 30_000;
const ROLES: [&str; 3] = ["implementer", "reviewer", "investigator"];
const READ_ONLY_ROLES: [&str; 2] = ["reviewer", "investigator"];

const SOURCE_DIR: &str = "scripts/copilot_agents";
const COPILOT_DIR: &str = "com.github.copilot/agents";
// Claude Code's default agents directory. Its manifest field takes only a list
// of .md files, and `claude plugin details` counted zero agents through it.
const CLAUDE_DIR: &str = "agents";
const TEMPLATE_DIR: &str = "skills/delegating-tasks-with-review-gates/reference";

/// Copilot's tool categories, as Claude Code spells them. Grep and Glob are
/// absent from some Claude Code builds; a listed tool the build lacks is not
/// offered, and Bash still searches.
const CLAUDE_TOOLS: [(&str, &[&str]); 4] = [
    ("execute", &["Bash"]),
    ("read", &["Read"]),
    ("search", &["Grep", "Glob"]),
    ("edit", &["Edit", "Write"]),
];

/// Added to every Claude Code agent's tools, whatever its Copilot categories.
const SKILL_TOOL: &str = "Skill";

fn header(name: &str) -> String {
    format!(
        "<!-- Generated by site/atelier agents from scripts/copilot_agents/{name}.md and \
         delegating-tasks-with-review-gates/reference/. Edit those, not this file. -->"
    )
}

/// The text between triple-backtick fences, one string per fenced block.
fn fenced_blocks(text: &str) -> Vec<String> {
    let mut blocks = Vec::new();
    let mut current: Option<Vec<&str>> = None;
    for line in text.split('\n') {
        if line.starts_with("```") {
            match current.take() {
                None => current = Some(Vec::new()),
                Some(lines) => blocks.push(lines.join("\n")),
            }
        } else if let Some(lines) = current.as_mut() {
            lines.push(line);
        }
    }
    blocks
}

/// The body of the `prompt: |` literal block, dedented four spaces.
fn dispatch_prompt(block: &str, label: &str) -> Result<String> {
    let marker = Regex::new(r"^\s*prompt:\s*\|\s*$").expect("static regex");
    let lines: Vec<&str> = block.split('\n').collect();
    let at = lines
        .iter()
        .position(|l| marker.is_match(l))
        .ok_or_else(|| anyhow!("{label}: no 'prompt: |' line in its first fenced block"))?;
    let body: Vec<&str> = lines[at + 1..]
        .iter()
        .map(|l| l.strip_prefix("    ").unwrap_or(l))
        .collect();
    Ok(body.join("\n").trim_end().to_string())
}

fn first_block(root: &Path, file: &str) -> Result<String> {
    let path = root.join(TEMPLATE_DIR).join(file);
    let text =
        std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
    fenced_blocks(&text)
        .into_iter()
        .next()
        .ok_or_else(|| anyhow!("{file}: no fenced block"))
}

/// The two tokens' replacement texts.
pub fn tokens(root: &Path) -> Result<Vec<(&'static str, String)>> {
    let implementer = dispatch_prompt(
        &first_block(root, "implementer-prompt.md")?,
        "implementer-prompt.md",
    )?;
    let anchor = "## You Do Not Dispatch Subagents";
    let cut = implementer
        .find(anchor)
        .ok_or_else(|| anyhow!("implementer-prompt.md: '{anchor}' not found"))?;
    let discipline =
        implementer[cut..].replace("[REPORT_FILE]", "the report file named in your task prompt");
    for heading in ["## Before Reporting Back: Self-Review", "## Report Format"] {
        if !discipline.contains(heading) {
            bail!("implementer-prompt.md: '{heading}' not found");
        }
    }
    let shared = first_block(root, "reviewer-prompt.md")?
        .trim_end()
        .to_string();
    for heading in [anchor, "## Do Not Trust the Report", "## Calibration"] {
        if !shared.contains(heading) {
            bail!("reviewer-prompt.md shared block: '{heading}' not found");
        }
    }
    Ok(vec![
        ("{{IMPLEMENTER_DISCIPLINE}}", discipline),
        ("{{REVIEWER_SHARED}}", shared),
    ])
}

/// The Copilot agents: file name (`<role>.agent.md`) to contents.
pub fn render(root: &Path) -> Result<BTreeMap<String, String>> {
    let tokens = tokens(root)?;
    let leftover = Regex::new(r"\{\{[A-Z_]+\}\}").expect("static regex");
    let source_dir = root.join(SOURCE_DIR);
    let mut sources: Vec<_> = std::fs::read_dir(&source_dir)
        .with_context(|| format!("reading {}", source_dir.display()))?
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|e| e == "md"))
        .collect();
    sources.sort();
    let mut out = BTreeMap::new();
    for source in sources {
        let stem = source
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or_default()
            .to_string();
        let file = format!("{stem}.md");
        let mut text = std::fs::read_to_string(&source)
            .with_context(|| format!("reading {}", source.display()))?
            .replace("\r\n", "\n")
            .replace("{{GENERATED_HEADER}}", &header(&stem));
        for (key, value) in &tokens {
            text = text.replace(key, value);
        }
        if let Some(left) = leftover.find(&text) {
            bail!("{file}: unresolved token {}", left.as_str());
        }
        let body = if text.starts_with("---\n") {
            text.split_once("\n---\n")
                .map(|(_, body)| body)
                .ok_or_else(|| anyhow!("{file}: frontmatter is never closed"))?
        } else {
            &text
        };
        let length = body.chars().count();
        if length > MAX_BODY {
            bail!("{file}: body is {length} chars, over Copilot's {MAX_BODY}");
        }
        out.insert(
            format!("{stem}.agent.md"),
            format!("{}\n", text.trim_end_matches('\n')),
        );
    }
    Ok(out)
}

/// The Claude Code agents: `<role>.md`, the same body with the tool list
/// translated.
pub fn render_claude(root: &Path) -> Result<BTreeMap<String, String>> {
    let tools_line = Regex::new(r"^tools:\s*\[(.*)\]\s*$").expect("static regex");
    let quoted = Regex::new(r#""([a-z]+)""#).expect("static regex");
    let mut out = BTreeMap::new();
    for (name, text) in render(root)? {
        let (head, body) = text
            .strip_prefix("---\n")
            .unwrap_or(&text)
            .split_once("\n---\n")
            .ok_or_else(|| anyhow!("{name}: frontmatter is never closed"))?;
        let mut lines = Vec::new();
        for line in head.split('\n') {
            let Some(found) = tools_line.captures(line) else {
                lines.push(line.to_string());
                continue;
            };
            let mut tools = Vec::new();
            let mut unknown = Vec::new();
            for category in quoted.captures_iter(&found[1]) {
                match CLAUDE_TOOLS.iter().find(|(c, _)| *c == &category[1]) {
                    Some((_, names)) => tools.extend(names.iter().copied()),
                    None => unknown.push(category[1].to_string()),
                }
            }
            if !unknown.is_empty() {
                bail!("{name}: no Claude Code tools for {unknown:?}");
            }
            // Skill is Claude Code's alone: without it these roles could not
            // use the library they ship in, and Copilot reaches a skill by
            // description instead.
            tools.push(SKILL_TOOL);
            lines.push(format!("tools: {}", tools.join(", ")));
        }
        let file = format!("{}.md", name.trim_end_matches(".agent.md"));
        out.insert(file, format!("---\n{}\n---\n{body}", lines.join("\n")));
    }
    Ok(out)
}

struct AgentSet {
    dir: &'static str,
    suffix: &'static str,
    render: fn(&Path) -> Result<BTreeMap<String, String>>,
}

const SETS: [AgentSet; 2] = [
    AgentSet {
        dir: COPILOT_DIR,
        suffix: ".agent.md",
        render,
    },
    AgentSet {
        dir: CLAUDE_DIR,
        suffix: ".md",
        render: render_claude,
    },
];

/// Every way the committed files differ from the render: `stale: <path>` for a
/// missing or different file, `no source: <path>` for one nothing renders.
pub fn staleness(root: &Path) -> Result<Vec<String>> {
    let mut problems = Vec::new();
    for set in &SETS {
        let rendered = (set.render)(root)?;
        let dir = root.join(set.dir);
        for (name, text) in &rendered {
            if std::fs::read_to_string(dir.join(name)).ok().as_deref() != Some(text.as_str()) {
                problems.push(format!("stale: {}/{name}", set.dir));
            }
        }
        if dir.is_dir() {
            let mut extra: Vec<String> = std::fs::read_dir(&dir)?
                .filter_map(Result::ok)
                .map(|e| e.file_name().to_string_lossy().into_owned())
                .filter(|n| n.ends_with(set.suffix) && !rendered.contains_key(n))
                .collect();
            extra.sort();
            problems.extend(
                extra
                    .into_iter()
                    .map(|n| format!("no source: {}/{n}", set.dir)),
            );
        }
    }
    Ok(problems)
}

/// `atelier-build agents [--check] [--root DIR]`: write both sets, or with
/// `--check` exit 1 naming whatever is stale.
pub fn run_agents(args: Vec<String>) -> ExitCode {
    let result = (|| -> Result<ExitCode> {
        let root = root_from(&args)?;
        if args.iter().any(|a| a == "--check") {
            let problems = staleness(&root)?;
            if problems.is_empty() {
                println!("agents up to date");
                return Ok(ExitCode::SUCCESS);
            }
            for problem in problems {
                println!("{problem}");
            }
            println!("run: atelier-build agents");
            return Ok(ExitCode::from(1));
        }
        for set in &SETS {
            let dir = root.join(set.dir);
            std::fs::create_dir_all(&dir)?;
            for (name, text) in (set.render)(&root)? {
                std::fs::write(dir.join(&name), text)?;
                println!("wrote {}/{name}", set.dir);
            }
        }
        Ok(ExitCode::SUCCESS)
    })();
    result.unwrap_or_else(|error| {
        eprintln!("atelier-build agents: {error:#}");
        ExitCode::from(2)
    })
}

/// `name: value` pairs of an agent's frontmatter.
fn frontmatter(text: &str) -> BTreeMap<String, String> {
    let line = Regex::new(r"^([\w-]+):\s*(.*)$").expect("static regex");
    let head = text.split("\n---\n").next().unwrap_or_default();
    head.strip_prefix("---\n")
        .unwrap_or(head)
        .split('\n')
        .filter_map(|l| line.captures(l))
        .map(|c| (c[1].to_string(), c[2].to_string()))
        .collect()
}

fn body(text: &str) -> &str {
    text.split_once("\n---\n").map_or("", |(_, body)| body)
}

/// Gate: the committed agents are exactly what the renderer writes.
pub fn fresh(repo: &Repo) -> Result<Vec<String>> {
    let mut problems = staleness(&repo.root)?;
    if !problems.is_empty() {
        problems.push("run: atelier-build agents".to_string());
    }
    Ok(problems)
}

/// Gate: each Copilot profile is well formed, the read-only roles cannot edit,
/// and the template text is embedded rather than paraphrased.
pub fn copilot_profiles(repo: &Repo) -> Result<Vec<String>> {
    let rendered = render(&repo.root)?;
    let mut problems = Vec::new();
    let expected: Vec<String> = {
        let mut names: Vec<String> = ROLES.iter().map(|r| format!("{r}.agent.md")).collect();
        names.sort();
        names
    };
    let found: Vec<&String> = rendered.keys().collect();
    if found
        .iter()
        .map(|s| s.as_str())
        .ne(expected.iter().map(String::as_str))
    {
        problems.push(format!(
            "the roles rendered are {found:?}, expected {expected:?}"
        ));
    }
    let manifest = repo.json("plugin.json")?;
    let declared = manifest["agents"].as_str().unwrap_or_default();
    if repo.path(declared).canonicalize().ok() != repo.path(COPILOT_DIR).canonicalize().ok() {
        problems.push(format!(
            "plugin.json: agents is {declared:?}, expected \"./{COPILOT_DIR}/\""
        ));
    }
    let tokens = tokens(&repo.root)?;
    for (name, text) in &rendered {
        let fm = frontmatter(text);
        let role = name.trim_end_matches(".agent.md");
        if fm.get("name").map(String::as_str) != Some(role) {
            problems.push(format!(
                "{name}: frontmatter name is {:?}, expected {role:?}",
                fm.get("name")
            ));
        }
        let description = fm.get("description").map_or("", String::as_str);
        if !description.contains("TBaguette") {
            problems.push(format!(
                "{name}: description does not say it is a TBaguette agent"
            ));
        }
        if !description.contains("Does not") {
            problems.push(format!("{name}: description must state its limits"));
        }
        if fm.contains_key("model") {
            problems.push(format!(
                "{name}: pins a model; the controller names one per dispatch, and a pinned id a plan \
                 does not offer breaks the agent"
            ));
        }
        if READ_ONLY_ROLES.contains(&role)
            && fm.get("tools").is_some_and(|t| t.contains("\"edit\""))
        {
            problems.push(format!("{role} must not be able to edit"));
        }
        if !text.contains("Edit those, not this file") {
            problems.push(format!("{name}: the generated header is missing"));
        }
    }
    for (name, token) in [
        ("implementer.agent.md", &tokens[0].1),
        ("reviewer.agent.md", &tokens[1].1),
    ] {
        if rendered
            .get(name)
            .is_some_and(|t| !t.contains(token.as_str()))
        {
            problems.push(format!(
                "{name}: the template text is not embedded verbatim"
            ));
        }
    }
    Ok(problems)
}

/// Gate: the Claude Code agents share the Copilot body and use Claude tool names.
pub fn claude_profiles(repo: &Repo) -> Result<Vec<String>> {
    let copilot = render(&repo.root)?;
    let claude = render_claude(&repo.root)?;
    let known: Vec<&str> = CLAUDE_TOOLS
        .iter()
        .flat_map(|(_, t)| t.iter().copied())
        .chain([SKILL_TOOL])
        .collect();
    let mut problems = Vec::new();
    let found: Vec<&String> = claude.keys().collect();
    let mut expected: Vec<String> = ROLES.iter().map(|r| format!("{r}.md")).collect();
    expected.sort();
    if found
        .iter()
        .map(|s| s.as_str())
        .ne(expected.iter().map(String::as_str))
    {
        problems.push(format!(
            "the roles rendered are {found:?}, expected {expected:?}"
        ));
    }
    for (name, text) in &claude {
        let role = name.trim_end_matches(".md");
        if copilot
            .get(&format!("{role}.agent.md"))
            .is_none_or(|c| body(c) != body(text))
        {
            problems.push(format!("{name}: body differs from the Copilot body"));
        }
        let fm = frontmatter(text);
        let tools: Vec<&str> = fm
            .get("tools")
            .map_or("", String::as_str)
            .split(',')
            .map(str::trim)
            .collect();
        if tools.iter().all(|t| t.is_empty()) || tools.iter().any(|t| !known.contains(t)) {
            problems.push(format!(
                "{name}: tools {tools:?} are not all Claude Code tool names"
            ));
        }
        if !tools.contains(&SKILL_TOOL) {
            problems.push(format!(
                "{name}: tools {tools:?} leave out {SKILL_TOOL}, so the role cannot use the skills"
            ));
        }
        if READ_ONLY_ROLES.contains(&role) {
            for forbidden in ["Edit", "Write"] {
                if tools.contains(&forbidden) {
                    problems.push(format!("{role} must not have {forbidden}"));
                }
            }
        }
        if fm.contains_key("model") {
            problems.push(format!("{name}: pins a model"));
        }
    }
    if claude.get("implementer.md").is_some_and(|t| {
        !frontmatter(t)
            .get("tools")
            .is_some_and(|t| t.contains("Edit"))
    }) {
        problems.push("implementer must have Edit".to_string());
    }
    Ok(problems)
}
