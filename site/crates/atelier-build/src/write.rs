//! Building the site into docs/ (scripts/generate.py's write path).
//!
//! Pages are rendered into a staging directory beside the output directory,
//! then each output path is swapped in by rename: a failed build leaves the
//! previous docs/ untouched, and each path is replaced atomically (the set as
//! a whole is not, as in the Python build). `docs/assets/` is hand-authored,
//! its files only hashed for the `?v=` fingerprints, apart from the two kinds
//! built: site/build.sh's WASM, and the hook's tables for the release card,
//! written here on every build.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::time::{SystemTime, UNIX_EPOCH};

use anyhow::{Context, Result, bail};
use atelier_core::graph::{self, BannerSummary, CitationList};
use atelier_core::highlight::highlight_source;
use atelier_core::model::categories;
use atelier_core::updates::UpdateEntry;
use chrono::{DateTime, Utc};
use sha2::{Digest, Sha256};

use crate::check::router::site_table;
use crate::pages::mods::{CLIMB_SLUG, ModsSite};
use crate::pages::{self, GRAPH_PATH, MODS_PATH, PageCtx};
use crate::repo;

/// The first line of every generated HTML page.
pub const GENERATED_HEADER: &str = "<!-- Generated by atelier-build — do not hand-edit. -->\n";

/// The number of skills the build expects (generate.py
/// `EXPECTED_SKILL_COUNT`): a skill added or removed by accident fails the
/// build instead of quietly changing the site.
pub const EXPECTED_SKILL_COUNT: usize = 103;

/// The assets pages link with a content fingerprint (generate.py
/// `VERSIONED_ASSETS`, plus each page's own stylesheet beside styles.css
/// (pages::shell::page_stylesheet) and the WASM front end site/build.sh writes: each
/// module's wasm-bindgen glue and its `.wasm`, which the page hands the glue
/// by its own fingerprinted URL). favicon.svg and the fonts are linked
/// without one. An asset not on disk is linked without a fingerprint.
pub const VERSIONED_ASSETS: [&str; 11] = [
    "styles.css",
    "landing.css",
    "graph.css",
    "mods.css",
    "site.js",
    "graph.js",
    "icons.svg",
    "atelier_web.js",
    "atelier_web_bg.wasm",
    "atelier_graph.js",
    "atelier_graph_bg.wasm",
];

/// The paths under docs/ the build owns and swaps in (generate.py's swap
/// set). Everything else there (the rest of assets/, superpowers/) is left alone.
pub const OUTPUTS: [&str; 8] = [
    "index.html",
    "skills",
    "verify-install",
    "getting-started",
    "graph",
    "mods",
    "version.txt",
    ROUTER_OUTPUT,
];

/// The hook's tables for the release card, under the output directory.
const ROUTER_OUTPUT: &str = "assets/skill-router.json";

/// How one build runs.
#[derive(Debug, Clone)]
pub struct BuildOptions {
    /// Prefixed verbatim to every root-relative URL: `/tbaguette-skills` for
    /// the published site, empty for serving at a domain root.
    pub base_path: String,
    /// The build instant. Precision beyond Python's microseconds is the
    /// caller's to drop.
    pub now: DateTime<Utc>,
    /// The revision whose git history decides the New/Updated badges:
    /// [`repo::HEAD`] for a real build (with the working tree's uncommitted
    /// changes on top), an older commit to reproduce the build made there.
    pub history_rev: String,
}

/// Builds the site from the repository at `root` into `out` (normally
/// `<root>/docs`), reading freshness from HEAD and the working tree.
pub fn build_site(root: &Path, out: &Path, base_path: &str, now: DateTime<Utc>) -> Result<()> {
    build_site_with(
        root,
        out,
        &BuildOptions {
            base_path: base_path.to_string(),
            now,
            history_rev: repo::HEAD.to_string(),
        },
    )
}

/// [`build_site`] with every option spelled out.
pub fn build_site_with(root: &Path, out: &Path, options: &BuildOptions) -> Result<()> {
    let site = read_site(root, options)?;
    fs::create_dir_all(out).with_context(|| format!("creating {}", out.display()))?;
    let parent = out
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    let staging = make_staging_dir(parent)?;
    if let Err(error) = render_into(&staging, &site) {
        let _ = fs::remove_dir_all(&staging);
        return Err(error);
    }
    swap_in(&staging, out, parent)
}

/// Everything one build renders from, read before anything is written.
struct Site {
    ctx: PageCtx,
    /// graph.json, packed.
    graph_json: String,
    graph_summary: BannerSummary,
    /// Who cites each skill and whom it cites (skill pages' strip and rail).
    citations: BTreeMap<String, CitationList>,
    notes: Vec<UpdateEntry>,
    /// The install test's source, highlighted line by line.
    install_test_lines: Vec<String>,
    /// /mods/ and its pages, from mods/ and the live climb log.
    mods: ModsSite,
    /// The hook's tables, for the release card to fetch.
    router_json: String,
}

/// Reads the repository, renders every skill's content and builds the
/// graph from the same skills.
fn read_site(root: &Path, options: &BuildOptions) -> Result<Site> {
    let skills = repo::load_skills(root)?;
    if skills.len() != EXPECTED_SKILL_COUNT {
        bail!(
            "expected {EXPECTED_SKILL_COUNT} skills, found {} under {}: refusing to build \
             against a schema drift. If a skill was deliberately added or removed, update \
             EXPECTED_SKILL_COUNT in atelier-build's write.rs.",
            skills.len(),
            root.join("skills").display()
        );
    }
    let fresh = repo::fresh_skills(root, options.now, &options.history_rev);
    // Fingerprinted from what this build writes, not from the copy on disk.
    let router_json = site_table(root)?;
    let mut versions = asset_versions(&root.join("docs/assets"))?;
    versions.insert(
        pages::unfold::ROUTER_ASSET.to_string(),
        fingerprint(router_json.as_bytes()),
    );
    let ctx = PageCtx::new(
        skills.clone(),
        categories(),
        &options.base_path,
        options.now,
        repo::plugin_version(root)?,
        versions,
        fresh,
    )?;
    // The graph is read back out of the same rendered bodies the skill pages
    // show, so an edge exists exactly where a reader can click one.
    let graph = graph::build(
        &skills,
        ctx.categories,
        &ctx.fresh,
        &ctx.skill_url("{slug}"),
    );
    let mods = ModsSite::read(
        &ctx,
        &repo::mods(root)?,
        repo::climb_live_log(root)?,
        repo::climb_live_meta(root)?,
    )?;
    Ok(Site {
        mods,
        graph_json: graph::to_json(&graph),
        graph_summary: graph::banner_summary(&graph),
        citations: graph::citation_lists(&graph),
        notes: repo::update_notes(root)?,
        install_test_lines: highlight_source(&repo::install_test_source(root)?),
        router_json,
        ctx,
    })
}

/// The first ten hex digits of each versioned asset's SHA-256, over its raw
/// bytes, for every one that exists (generate.py `asset_versions`). Content
/// rather than build time: an unchanged stylesheet keeps the URL a reader has
/// cached.
pub fn asset_versions(assets_dir: &Path) -> Result<BTreeMap<String, String>> {
    let mut versions = BTreeMap::new();
    for name in VERSIONED_ASSETS {
        let path = assets_dir.join(name);
        if !path.is_file() {
            continue;
        }
        let bytes = fs::read(&path).with_context(|| format!("reading {}", path.display()))?;
        versions.insert(name.to_string(), fingerprint(&bytes));
    }
    Ok(versions)
}

/// The first ten hex digits of the content's SHA-256.
fn fingerprint(bytes: &[u8]) -> String {
    let hex: String = Sha256::digest(bytes)
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect();
    hex[..10].to_string()
}

/// Writes every output into `staging`: the pages, graph.json and the hook's
/// tables (no header: a comment would make them invalid JSON) and version.txt
/// (the build instant, no newline; site.js polls it).
fn render_into(staging: &Path, site: &Site) -> Result<()> {
    let ctx = &site.ctx;
    write_file(&staging.join(ROUTER_OUTPUT), &site.router_json)?;
    let graph_dir = staging.join(GRAPH_PATH);
    write_file(
        &graph_dir.join(pages::other::GRAPH_DATA_FILENAME),
        &site.graph_json,
    )?;
    write_page(
        &graph_dir.join("index.html"),
        &pages::other::graph_page(ctx, &site.graph_summary),
    )?;
    write_page(
        &staging.join("index.html"),
        &pages::index::render(ctx, &site.notes, &site.graph_summary, &site.mods.names()),
    )?;
    for slug in ctx.skills.keys() {
        let html = pages::skill::render(ctx, slug, site.citations.get(slug));
        write_page(&staging.join("skills").join(slug).join("index.html"), &html)?;
    }
    write_page(
        &staging.join("verify-install/index.html"),
        &pages::other::verify_install(ctx, &site.install_test_lines),
    )?;
    write_page(
        &staging.join(pages::GETTING_STARTED_PATH).join("index.html"),
        &pages::other::getting_started(ctx),
    )?;
    let mods_dir = staging.join(MODS_PATH);
    write_page(
        &mods_dir.join("index.html"),
        &pages::mods::index(ctx, &site.mods),
    )?;
    write_page(
        &mods_dir.join(CLIMB_SLUG).join("index.html"),
        &pages::mods::climb(ctx, &site.mods),
    )?;
    for slug in site.mods.plain_slugs() {
        let page = pages::mods::plain(ctx, &site.mods, &slug)
            .ok_or_else(|| anyhow::anyhow!("mods/{slug}: no page was built"))?;
        write_page(&mods_dir.join(&slug).join("index.html"), &page)?;
    }
    write_file(&staging.join("version.txt"), &ctx.last_updated_utc())
}

/// Writes one HTML page, with the generated-file header, creating its
/// directory.
fn write_page(path: &Path, html: &str) -> Result<()> {
    write_file(path, &format!("{GENERATED_HEADER}{html}"))
}

/// Writes `text` to `path` as is, creating its directory.
fn write_file(path: &Path, text: &str) -> Result<()> {
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
    }
    fs::write(path, text).with_context(|| format!("writing {}", path.display()))
}

/// `<parent>/.docs.build.<unique>`, created empty.
fn make_staging_dir(parent: &Path) -> Result<PathBuf> {
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |d| d.subsec_nanos());
    let dir = parent.join(format!(".docs.build.{}-{nanos:09}", std::process::id()));
    fs::create_dir(&dir).with_context(|| format!("creating {}", dir.display()))?;
    Ok(dir)
}

/// Replaces each output under `out` with its staged copy: the old one is
/// renamed to `<parent>/.docs.previous.<name>`, the new one renamed in, the
/// old one deleted (generate.py's swap loop).
fn swap_in(staging: &Path, out: &Path, parent: &Path) -> Result<()> {
    for name in OUTPUTS {
        let target = out.join(name);
        let backup = parent.join(format!(".docs.previous.{}", name.replace('/', "-")));
        remove_path(&backup)?;
        if let Some(dir) = target.parent() {
            fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
        }
        if target.exists() {
            fs::rename(&target, &backup)
                .with_context(|| format!("moving {} aside", target.display()))?;
        }
        fs::rename(staging.join(name), &target)
            .with_context(|| format!("moving the new {name} into {}", out.display()))?;
        remove_path(&backup)?;
    }
    fs::remove_dir_all(staging).with_context(|| format!("removing {}", staging.display()))
}

fn remove_path(path: &Path) -> Result<()> {
    let result = if path.is_dir() {
        fs::remove_dir_all(path)
    } else if path.exists() {
        fs::remove_file(path)
    } else {
        return Ok(());
    };
    result.with_context(|| format!("removing {}", path.display()))
}
